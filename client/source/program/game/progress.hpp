#pragma once

#include <common.hpp>

/* Shared progress: shrines found/activated/cleared, towers, Divine Beasts and
   Koroks. The list of flags comes from content:/botw-coop/sync-flags.txt
   (generated by tools/build_romfs_mod.py). When one of them turns true in
   this game it's sent to everyone; flags received from others are set here.
   Flags are only ever set, never cleared. */
namespace coop::game::progress {

    /* Startup: reads the flag list and hooks the game's flag writes. */
    void Install();

    /* Game thread, every tick while in the world. */
    void Tick();

    /* Network thread: another player set a flag. `live` = they just earned it
       (gives you the reward too); false = catch-up for a late joiner. */
    void OnRemoteFlag(u8 from, const char* name, size_t len, bool live);

    /* Share Divine Beast clears with partners anywhere (default: only with
       partners inside the beast with you; see the guards in Tick). */
    void SetBeastsAnywhere(bool on);
    /* Debug: use this flag instead of the paraglider as "the tutorial is over". */
    void SetTestGate(const char* flag);

    /* Network thread: someone joined; send them everything we've done. */
    void OnPlayerJoined(); /* also called when we join a room that already has players */

    /* Debug: set this flag locally once connected, as if the game had. */
    void SetTestFlag(const char* name);

    /* Debug: open the pause menu 2 s after a partner's reward, to show it. */
    void SetTestMenu(bool on);
    bool TestMenu();
}
