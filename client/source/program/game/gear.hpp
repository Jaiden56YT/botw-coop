#pragma once

#include <common.hpp>

/* What each player is wearing. Link's worn armor pieces are separate actors
   sitting on him (Armor_<id>_Head/_Upper/_Lower); each game sends their names,
   and other games show the matching CoopGear_<model> actors on that player's
   puppet (the armor -> model table is content:/botw-coop/gear-map.txt,
   generated by tools/build_romfs_mod.py). */
namespace coop::game::gear {

    constexpr int Slots = 3; /* head, upper, lower */
    constexpr int NameLen = 32;

    /* Game thread, every tick: notices what Link is wearing and sends changes. */
    void Tick(s64 now_ms);

    /* The gear actor to show for an armor actor name ("Armor_151_Upper" ->
       "CoopGear_Armor_116_Upper"), or false if unknown. */
    bool GearActorFor(const char* armor, char (&out)[64]);
}
